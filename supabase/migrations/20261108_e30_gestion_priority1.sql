-- Una creación de orden y su seña inicial se guardan juntas en una transacción.
create or replace function public.e30_crear_orden(p_orden jsonb, p_sena numeric default 0, p_medio text default 'Efectivo')
returns bigint
language plpgsql
security invoker
set search_path = pg_catalog, public
as $$
declare v_id bigint; v_total numeric;
begin
  v_total := coalesce((p_orden->>'total')::numeric, 0);
  if coalesce(p_sena, 0) < 0 or coalesce(p_sena, 0) > v_total then raise exception 'La seña debe estar entre cero y el total.'; end if;
  insert into public.ordenes (cliente_id, cliente, telefono, negocio, tipo, marca, modelo, falla, estado, total, notas, imei)
  values ((p_orden->>'cliente_id')::uuid, p_orden->>'cliente', p_orden->>'telefono', p_orden->>'negocio', 'Particular', p_orden->>'marca', p_orden->>'modelo', p_orden->>'falla', coalesce(p_orden->>'estado', 'Recibido'), v_total, p_orden->>'notas', p_orden->>'imei')
  returning id into v_id;
  if coalesce(p_sena, 0) > 0 then
    insert into public.pagos (orden_id, importe, medio) values (v_id, p_sena, coalesce(nullif(p_medio, ''), 'Efectivo'));
  end if;
  return v_id;
end;
$$;
revoke all on function public.e30_crear_orden(jsonb, numeric, text) from public, anon;
grant execute on function public.e30_crear_orden(jsonb, numeric, text) to authenticated;

create or replace function public.e30_registrar_pago(p_orden_id bigint, p_importe numeric, p_medio text default 'Efectivo')
returns bigint
language plpgsql
security invoker
set search_path = pg_catalog, public
as $$
declare v_total numeric; v_pagado numeric; v_id bigint;
begin
  select total into v_total from public.ordenes where id = p_orden_id for update;
  if not found then raise exception 'No se encontró la orden.'; end if;
  if p_importe is null or p_importe <= 0 then raise exception 'El pago debe ser mayor que cero.'; end if;
  if coalesce(p_medio, '') not in ('Efectivo', 'Transferencia', 'Mercado Pago', 'Tarjeta') then raise exception 'Medio de pago no válido.'; end if;
  select coalesce(sum(importe), 0) into v_pagado from public.pagos where orden_id = p_orden_id;
  if v_pagado + p_importe > v_total then raise exception 'El pago supera el saldo pendiente.'; end if;
  insert into public.pagos (orden_id, importe, medio) values (p_orden_id, p_importe, p_medio) returning id into v_id;
  return v_id;
end;
$$;
revoke all on function public.e30_registrar_pago(bigint, numeric, text) from public, anon;
grant execute on function public.e30_registrar_pago(bigint, numeric, text) to authenticated;

