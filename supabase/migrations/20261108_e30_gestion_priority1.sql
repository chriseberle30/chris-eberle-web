create or replace function public.e30_registrar_historial_orden()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  v_evento text;
  v_detalle text;
begin
  if tg_op = 'INSERT' then
    v_evento := 'Orden creada';
    v_detalle := concat_ws(' · ', nullif(new.negocio, ''), nullif(new.modelo, ''), nullif(new.estado, ''));
  elsif old.borrada is null and new.borrada is not null then
    v_evento := 'Orden enviada a papelera';
    v_detalle := 'La orden se conservó y puede restaurarse.';
  elsif old.borrada is not null and new.borrada is null then
    v_evento := 'Orden restaurada';
    v_detalle := 'La orden volvió a la lista activa.';
  elsif old.estado is distinct from new.estado then
    v_evento := 'Estado actualizado';
    v_detalle := old.estado || ' → ' || new.estado;
  else
    v_evento := 'Orden actualizada';
    v_detalle := 'Se actualizaron los datos de reparación.';
  end if;

  insert into public.orden_historial (orden_id, evento, detalle, actor)
  values (new.id, v_evento, v_detalle, auth.uid());
  return new;
end;
$$;

drop trigger if exists e30_orden_historial on public.ordenes;
create trigger e30_orden_historial
after insert or update on public.ordenes
for each row execute function public.e30_registrar_historial_orden();

