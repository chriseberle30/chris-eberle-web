-- Enlazado gradual: las columnas cliente/telefono anteriores no se borran.
insert into public.clientes (nombre, telefono, legacy_key)
select distinct on (lower(btrim(o.cliente)), coalesce(nullif(regexp_replace(o.telefono, '\D', '', 'g'), ''), 'orden:' || o.id::text))
  btrim(o.cliente), nullif(btrim(o.telefono), ''),
  lower(btrim(o.cliente)) || chr(31) || coalesce(nullif(regexp_replace(o.telefono, '\D', '', 'g'), ''), 'orden:' || o.id::text)
from public.ordenes o
where nullif(btrim(o.cliente), '') is not null
order by lower(btrim(o.cliente)), coalesce(nullif(regexp_replace(o.telefono, '\D', '', 'g'), ''), 'orden:' || o.id::text), o.id
on conflict do nothing;

update public.ordenes o
set cliente_id = (
  select c.id from public.clientes c
  where c.legacy_key = lower(btrim(o.cliente)) || chr(31) || coalesce(nullif(regexp_replace(o.telefono, '\D', '', 'g'), ''), 'orden:' || o.id::text)
  limit 1
)
where o.cliente_id is null and nullif(btrim(o.cliente), '') is not null;

